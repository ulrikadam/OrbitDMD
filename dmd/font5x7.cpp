const char * const *FontGetGlyph (char chChar)
{
	if ('a' <= chChar && chChar <= 'z')
	{
		chChar = chChar - 'a' + 'A';
	}

	for (unsigned i = 0; i < sizeof s_Glyphs / sizeof s_Glyphs[0]; i++)
	{
		if (s_Glyphs[i].chChar == chChar)
		{
			return s_Glyphs[i].Rows;
		}
	}

	return 0;
}
