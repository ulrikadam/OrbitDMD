// lettres accentuees latines (0xC0 a 0xDE, majuscules) -> lettre simple
static const char s_Fold[] = "AAAA*AACEEEEIIIIDNOOOO**OUUU*YP";	// * : lettre dessinee (Ä Ö Ü)

// U+0100 a U+017F (polonais, tcheque, turc...) -> lettre simple
static const char s_FoldExtA[] = "AAAAAACCCCCCCCDDDDEEEEEEEEEEGGGGGGGGHHHHIIIIIIIIIIIIJJKKKLLLLLLLLLLNNNNNNNNNOOOOOOOORRRRRRSSSSSSSSTTTTTTUUUUUUUUUUUUWWYYYZZZZZZS";

// cyrillique de meme forme que le latin
static const struct { unsigned nCode; char chLatin; } s_Alias[] =
{
	{0x410, 'A'}, {0x412, 'B'}, {0x415, 'E'}, {0x41A, 'K'}, {0x41C, 'M'}, {0x41D, 'H'},
	{0x41E, 'O'}, {0x420, 'P'}, {0x421, 'C'}, {0x422, 'T'}, {0x425, 'X'}, {0x406, 'I'}
};

const char * const *FontGetGlyph (unsigned nCode)
{
	// minuscules -> majuscules
	if ('a' <= nCode && nCode <= 'z')			nCode -= 'a' - 'A';
	else if (0xE0 <= nCode && nCode <= 0xFE && nCode != 0xF7)	nCode -= 0x20;
	else if (0x430 <= nCode && nCode <= 0x44F)		nCode -= 0x20;
	else if (0x450 <= nCode && nCode <= 0x45F)		nCode -= 0x50;		// yo, ukrainien
	else if (nCode == 0x491)				nCode = 0x490;		// ghe ukrainien
	else if (nCode == 0x1E9E)				nCode = 0xDF;		// eszett majuscule

	if (0x100 <= nCode && nCode <= 0x17F)
	{
		nCode = (unsigned char) s_FoldExtA[nCode - 0x100];
	}

	if (0xC0 <= nCode && nCode <= 0xDE && nCode != 0xD1 && s_Fold[nCode - 0xC0] != '*')
	{
		nCode = (unsigned char) s_Fold[nCode - 0xC0];
	}
	for (unsigned i = 0; i < sizeof s_Alias / sizeof s_Alias[0]; i++)
	{
		if (s_Alias[i].nCode == nCode)
		{
			nCode = (unsigned char) s_Alias[i].chLatin;
			break;
		}
	}

	int nLow = 0, nHigh = (int) (sizeof s_Glyphs / sizeof s_Glyphs[0]) - 1;
	while (nLow <= nHigh)
	{
		int nMiddle = (nLow + nHigh) / 2;
		if (s_Glyphs[nMiddle].nCode == nCode)
		{
			return s_Glyphs[nMiddle].Rows;
		}
		if (s_Glyphs[nMiddle].nCode < nCode)	nLow = nMiddle + 1;
		else					nHigh = nMiddle - 1;
	}

	return 0;
}

unsigned Utf8Next (const char **ppText)
{
	const unsigned char *p = (const unsigned char *) *ppText;
	unsigned nCode = *p++;

	if (nCode >= 0x80)
	{
		unsigned nMore = (nCode & 0xE0) == 0xC0 ? 1 : (nCode & 0xF0) == 0xE0 ? 2 : (nCode & 0xF8) == 0xF0 ? 3 : 0;
		unsigned nValue = nCode & (0x3F >> nMore);
		unsigned i;
		for (i = 0; i < nMore && (p[i] & 0xC0) == 0x80; i++)
		{
			nValue = nValue << 6 | (p[i] & 0x3F);
		}
		if (nMore > 0 && i == nMore)
		{
			nCode = nValue;
			p += nMore;
		}
		// sinon : octet isole, garde tel quel (ancien texte en Latin-1)
	}

	*ppText = (const char *) p;
	return nCode;
}

unsigned Utf8Length (const char *pText)
{
	unsigned n = 0;
	while (*pText != '\0')
	{
		Utf8Next (&pText);
		n++;
	}

	return n;
}

const char *Utf8Skip (const char *pText, unsigned nChars)
{
	while (nChars-- > 0 && *pText != '\0')
	{
		Utf8Next (&pText);
	}

	return pText;
}
